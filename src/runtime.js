import { mkdir, writeFile, access, lstat, realpath, rename, chmod } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const RUNTIME = path.join(ROOT, 'runtime');
export const WORKSPACE = path.join(ROOT, 'fixture-workspace');
export const CODEX_HOME = path.join(RUNTIME, 'codex-home');

// Deliberate allowlist. Never inherit API keys, auth tokens, proxy passwords,
// session paths, NODE_OPTIONS, or the host user's HOME/CODEX_HOME.
export function isolatedEnv(base = process.env) {
  const env = {};
  for (const key of ['PATH', 'SystemRoot', 'WINDIR', 'COMSPEC', 'PATHEXT', 'LANG', 'LC_ALL']) {
    if (base[key]) env[key] = base[key];
  }
  return Object.assign(env, {
    HOME: path.join(RUNTIME, 'home'), USERPROFILE: path.join(RUNTIME, 'home'),
    CODEX_HOME, TMPDIR: path.join(RUNTIME, 'tmp'), TMP: path.join(RUNTIME, 'tmp'),
    TEMP: path.join(RUNTIME, 'tmp'), XDG_CONFIG_HOME: path.join(RUNTIME, 'home', '.config'),
    XDG_CACHE_HOME: path.join(RUNTIME, 'home', '.cache'),
  });
}
export async function assertSafePath(target, directory = false) {
  const relative = path.relative(ROOT, target);
  if (relative.startsWith('..') || path.isAbsolute(relative)) throw new Error('Path outside project');
  let current = ROOT;
  for (const part of relative.split(path.sep).filter(Boolean)) {
    current = path.join(current, part);
    try {
      const stat = await lstat(current);
      if (stat.isSymbolicLink()) throw new Error('Symlink refused in project runtime');
      if (process.getuid && stat.uid !== process.getuid()) throw new Error('Runtime path is not owned by current user');
    } catch (e) { if (e.code !== 'ENOENT') throw e; }
  }
  if (directory) {
    const canonicalRoot = await realpath(ROOT);
    const canonical = await realpath(target);
    if (canonical !== canonicalRoot && !canonical.startsWith(canonicalRoot + path.sep)) throw new Error('Runtime escaped project');
  }
}
export async function prepareRuntime() {
  for (const dir of [RUNTIME, CODEX_HOME, path.join(RUNTIME, 'home'), path.join(RUNTIME, 'tmp'), WORKSPACE]) {
    await assertSafePath(dir);
    await mkdir(dir, { recursive: true, mode: 0o700 });
    await assertSafePath(dir, true);
    if (dir !== WORKSPACE) await chmod(dir, 0o700);
  }
  const config = path.join(CODEX_HOME, 'config.toml');
  await assertSafePath(config);
  const temporary = path.join(CODEX_HOME, `.config-${randomUUID()}.tmp`);
  // This generated config is owned by this app, not ~/.codex.
  await writeFile(temporary, `# Generated by local control-panel. Separate config is not an OS sandbox.\nsandbox_mode = "read-only"\napproval_policy = "on-request"\nweb_search = "disabled"\ncli_auth_credentials_store = "file"\n[analytics]\nenabled = false\n[agents]\nenabled = false\n[features]\nshell_tool = false\n`, { mode: 0o600, flag: 'wx' });
  await rename(temporary, config);
}
export async function codexCommand() {
  // An administrator may select a binary via the local process environment;
  // this is deliberately not accepted from HTTP.
  if (process.env.CONTROL_PANEL_CODEX_BIN) {
    const binary = path.resolve(process.env.CONTROL_PANEL_CODEX_BIN);
    if (/\.(cmd|bat)$/i.test(binary)) throw new Error('Windows 请指定官方 codex.exe 或使用 WSL，不能用 shell 执行 .cmd/.bat');
    await access(binary);
    return binary;
  }
  // Prefer the installed CLI on PATH. Never download or npx-install implicitly.
  return 'codex';
}
export async function cliVersion(command = null) {
  await assertSafePath(WORKSPACE, true);
  await assertSafePath(CODEX_HOME, true);
  const binary = command || await codexCommand();
  const r = spawnSync(binary, ['--version'], {
    cwd: WORKSPACE, env: isolatedEnv(), encoding: 'utf8', timeout: 10000,
    windowsHide: true, shell: false,
  });
  if (r.error || r.status !== 0) throw new Error('Codex CLI 未找到或无法启动。请在终端安装官方 CLI，或配置 CONTROL_PANEL_CODEX_BIN。');
  return r.stdout.trim().slice(0, 120);
}
